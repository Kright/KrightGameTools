package me.kright.gametools.pga2d

import me.kright.gametools.flatarray.FlatDoubleSerializer
import me.kright.gametools.mathutil.CanEqualWithEps

/**
 * A cached form of a motor: the sandwich and reverseSandwich products expressed as precomputed matrices.
 *
 * Prefer this class over motor.sandwich whenever the same motor is applied to many objects -
 * moving all the points of a body, transforming forces and velocities in a physics solver step, etc.
 * Building the transform costs about as much as a single motor sandwich, and after that every
 * application is a plain matrix multiplication, several times cheaper than motor.sandwich,
 * which recomputes the coefficients on every call.
 *
 * The class is immutable, like the Pga2dMotor it is built around.
 *
 * Cached values:
 *  - r00, r01: the two independent entries of the 2x2 rotation matrix [[r00, r01], [-r01, r00]],
 *    the cosine and sine of the rotation angle scaled by motor.normSquare; the reverse
 *    transformation uses the transpose.
 *  - tx, ty and txRev, tyRev: translation for points, forward and reverse.
 *  - normSquare: the squared norm of the motor, the weight of the resulting projective point.
 *
 * The results are equivalent to motor.sandwich(r) / motor.reverseSandwich(r) up to floating point
 * rounding for any motor, normalized or not. See [[Pga2dTransform]] for the
 * normalized-motor variant with narrower result types.
 *
 * Generated by pgaNdCodeGen (me.kright.gametools.pga.codegen.scalagen.pga2d.runScalaCodeGen).
 * Do not edit by hand: change the generator and re-run it.
 */
final case class Pga2dProjectiveTransform(motor: Pga2dMotor,

                                          r00: Double, r01: Double,

                                          normSquare: Double,

                                          tx: Double, ty: Double,
                                          txRev: Double, tyRev: Double) derives CanEqual, CanEqualWithEps, FlatDoubleSerializer:

  override def toString: String =
    s"Pga2dProjectiveTransform($motor)"

  infix def sandwich(r: Pga2dMotor): Pga2dMotor =
    Pga2dMotor(
      s = normSquare * r.s,
      wx = (r.wx * r00 + r.wy * r01 + r.xy * ty),
      wy = (r.wy * r00 - r.wx * r01 - r.xy * tx),
      xy = normSquare * r.xy,
    )

  infix def reverseSandwich(r: Pga2dMotor): Pga2dMotor =
    Pga2dMotor(
      s = normSquare * r.s,
      wx = (r.wx * r00 + r.xy * tyRev - r.wy * r01),
      wy = (r.wx * r01 + r.wy * r00 - r.xy * txRev),
      xy = normSquare * r.xy,
    )

  infix def sandwich(r: Pga2dLine): Pga2dLine =
    Pga2dLine(
      x = (r.x * r00 + r.y * r01),
      y = (r.y * r00 - r.x * r01),
      w = (normSquare * r.w + r.x * txRev + r.y * tyRev),
    )

  infix def reverseSandwich(r: Pga2dLine): Pga2dLine =
    Pga2dLine(
      x = (r.x * r00 - r.y * r01),
      y = (r.x * r01 + r.y * r00),
      w = (normSquare * r.w + r.x * tx + r.y * ty),
    )

  infix def sandwich(r: Pga2dRotor): Pga2dMotor =
    Pga2dMotor(
      s = normSquare * r.s,
      wx = r.xy * ty,
      wy = -r.xy * tx,
      xy = normSquare * r.xy,
    )

  infix def reverseSandwich(r: Pga2dRotor): Pga2dMotor =
    Pga2dMotor(
      s = normSquare * r.s,
      wx = r.xy * tyRev,
      wy = -r.xy * txRev,
      xy = normSquare * r.xy,
    )

  infix def sandwich(r: Pga2dProjectivePoint): Pga2dProjectivePoint =
    Pga2dProjectivePoint(
      x = (r.w * tx + r.x * r00 + r.y * r01),
      y = (r.w * ty + r.y * r00 - r.x * r01),
      w = normSquare * r.w,
    )

  infix def reverseSandwich(r: Pga2dProjectivePoint): Pga2dProjectivePoint =
    Pga2dProjectivePoint(
      x = (r.w * txRev + r.x * r00 - r.y * r01),
      y = (r.w * tyRev + r.x * r01 + r.y * r00),
      w = normSquare * r.w,
    )

  infix def sandwich(r: Pga2dProjectiveTranslator): Pga2dProjectiveTranslator =
    Pga2dProjectiveTranslator(
      s = normSquare * r.s,
      wx = (r.wx * r00 + r.wy * r01),
      wy = (r.wy * r00 - r.wx * r01),
    )

  infix def reverseSandwich(r: Pga2dProjectiveTranslator): Pga2dProjectiveTranslator =
    Pga2dProjectiveTranslator(
      s = normSquare * r.s,
      wx = (r.wx * r00 - r.wy * r01),
      wy = (r.wx * r01 + r.wy * r00),
    )

  infix def sandwich(r: Pga2dTranslator): Pga2dProjectiveTranslator =
    Pga2dProjectiveTranslator(
      s = normSquare,
      wx = (r.wx * r00 + r.wy * r01),
      wy = (r.wy * r00 - r.wx * r01),
    )

  infix def reverseSandwich(r: Pga2dTranslator): Pga2dProjectiveTranslator =
    Pga2dProjectiveTranslator(
      s = normSquare,
      wx = (r.wx * r00 - r.wy * r01),
      wy = (r.wx * r01 + r.wy * r00),
    )

  infix def sandwich(r: Pga2dVector): Pga2dVector =
    Pga2dVector(
      x = (r.x * r00 + r.y * r01),
      y = (r.y * r00 - r.x * r01),
    )

  infix def reverseSandwich(r: Pga2dVector): Pga2dVector =
    Pga2dVector(
      x = (r.x * r00 - r.y * r01),
      y = (r.x * r01 + r.y * r00),
    )

  infix def sandwich(r: Pga2dPoint): Pga2dProjectivePoint =
    Pga2dProjectivePoint(
      x = (tx + r.x * r00 + r.y * r01),
      y = (ty + r.y * r00 - r.x * r01),
      w = normSquare,
    )

  infix def reverseSandwich(r: Pga2dPoint): Pga2dProjectivePoint =
    Pga2dProjectivePoint(
      x = (txRev + r.x * r00 - r.y * r01),
      y = (tyRev + r.x * r01 + r.y * r00),
      w = normSquare,
    )

  infix def sandwich(r: Pga2dLineCentral): Pga2dLine =
    Pga2dLine(
      x = (r.x * r00 + r.y * r01),
      y = (r.y * r00 - r.x * r01),
      w = (r.x * txRev + r.y * tyRev),
    )

  infix def reverseSandwich(r: Pga2dLineCentral): Pga2dLine =
    Pga2dLine(
      x = (r.x * r00 - r.y * r01),
      y = (r.x * r01 + r.y * r00),
      w = (r.x * tx + r.y * ty),
    )

  infix def sandwich(r: Pga2dPseudoScalar): Pga2dPseudoScalar =
    Pga2dPseudoScalar(
      i = normSquare * r.i,
    )

  infix def reverseSandwich(r: Pga2dPseudoScalar): Pga2dPseudoScalar =
    Pga2dPseudoScalar(
      i = normSquare * r.i,
    )

  infix def sandwich(r: Pga2dPointCenter.type): Pga2dProjectivePoint =
    Pga2dProjectivePoint(
      x = tx,
      y = ty,
      w = normSquare,
    )

  infix def reverseSandwich(r: Pga2dPointCenter.type): Pga2dProjectivePoint =
    Pga2dProjectivePoint(
      x = txRev,
      y = tyRev,
      w = normSquare,
    )


object Pga2dProjectiveTransform:
  val id: Pga2dProjectiveTransform = Pga2dProjectiveTransform(Pga2dMotor.id)

  def apply(motor: Pga2dMotor): Pga2dProjectiveTransform =
    val s = motor.s
    val wx = motor.wx
    val wy = motor.wy
    val xy = motor.xy

    val sMs = s * s
    val sMwx = s * wx
    val sMwy = s * wy
    val wxMxy = wx * xy
    val wyMxy = wy * xy
    val xyMxy = xy * xy

    new Pga2dProjectiveTransform(
      motor,

      r00 = (sMs - xyMxy),
      r01 = 2.0 * s * xy,

      normSquare = (sMs + xyMxy),

      tx = 2.0 * (-sMwx - wyMxy),
      ty = 2.0 * (wxMxy - sMwy),
      txRev = 2.0 * (sMwx - wyMxy),
      tyRev = 2.0 * (sMwy + wxMxy),
    )